#!/usr/bin/env python3
"""Compile the runtime's own shaders to SPIR-V and embed them in headers (committed, so a build needs no shader
compiler). Run after editing a shader.

  runtime/shaders/*.vert|*.frag    -> runtime/src/shaders_spv.h
  runtime/shaders/post/*.comp       -> runtime/src/nvn/post_spv.h   (FSR 1 with third_party/fsr1, FXAA)

Usage: python tools/gen_shaders.py [glslc] [--only <header name part>]
       (glslc: default the Android NDK's, or glslc on PATH; --only post regenerates post_spv.h alone)
"""
import glob
import os
import shutil
import struct
import subprocess
import sys
import tempfile

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# (sources, header, extra glslc arguments)
OUTPUTS = [
    (os.path.join('runtime', 'shaders', '*.*'), os.path.join('runtime', 'src', 'shaders_spv.h'), []),
    (os.path.join('runtime', 'shaders', 'post', '*.comp'), os.path.join('runtime', 'src', 'nvn', 'post_spv.h'),
     ['-I', os.path.join(root, 'third_party', 'fsr1')]),
]


def find_glslc(args):
    if args:
        return args[0]
    sdk = os.environ.get('ANDROID_HOME', os.path.expanduser('~/Library/Android/sdk'))
    for p in sorted(glob.glob(os.path.join(sdk, 'ndk', '*', 'shader-tools', '*', 'glslc*'))):
        return p
    return shutil.which('glslc') or sys.exit('glslc not found (Android NDK shader-tools or Vulkan SDK)')


def embed(glslc, pattern, header, extra):
    out = [f'// Generated by tools/gen_shaders.py from {os.path.dirname(pattern)}. Do not edit.', '#pragma once',
           '#include <cstdint>', '']
    for src in sorted(glob.glob(os.path.join(root, pattern))):
        if os.path.isdir(src):
            continue
        name = os.path.basename(src).replace('.', '_')
        with tempfile.TemporaryDirectory() as d:
            spv = os.path.join(d, 'out.spv')
            subprocess.run([glslc, '-O', '--target-env=vulkan1.0', *extra, src, '-o', spv], check=True)
            data = open(spv, 'rb').read()
        words = struct.unpack(f'<{len(data) // 4}I', data)
        out.append(f'inline constexpr uint32_t k_{name}[] = {{')
        for i in range(0, len(words), 8):
            out.append('    ' + ', '.join(f'0x{w:08x}' for w in words[i:i + 8]) + ',')
        out.append('};')
        out.append('')
        print(f'{os.path.basename(src)}: {len(data)} bytes')
    open(os.path.join(root, header), 'w').write('\n'.join(out))


def main():
    args = sys.argv[1:]
    only = None
    if '--only' in args:
        i = args.index('--only')
        only = args[i + 1]
        del args[i:i + 2]
    glslc = find_glslc(args)
    for pattern, header, extra in OUTPUTS:
        if only is None or only in header:
            embed(glslc, pattern, header, extra)


if __name__ == '__main__':
    main()
